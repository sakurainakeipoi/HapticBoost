# ============================================================
#  HapticBoost — 默认配置模板
#  （App「震动增强」会覆盖本文件；也可以手动编辑）
# ============================================================
#  单位：mV，硬件上限 9500
#
#  三条可调通路（本机的关键发现）：
#    vmax      = 普通震动（oneshot / 通知 / App 震动）
#    fifo_vmax = 触感反馈（点按、滑动、系统交互）
#    cl_vmax   = 闭环 / 恒定反馈（部分长震走这里）
# ============================================================

# ---------- 日常场景 ----------
NORMAL_VMAX=5500          # 日常 · 普通震动
NORMAL_FIFO_VMAX=4800     # 日常 · 触感反馈
NORMAL_CL_VMAX=1280       # 日常 · 闭环

# ---------- 来电响铃场景 ----------
CALL_VMAX=9500            # 响铃 · 普通震动
CALL_FIFO_VMAX=9500       # 响铃 · 触感反馈
CALL_CL_VMAX=9500         # 响铃 · 闭环

# ---------- 行为开关 ----------
CALL_BOOST=1              # 来电增强总开关；App 会与 RING_PLAY 保持一致
POLL=1                    # 场景监听轮询间隔（秒）
HOLD=0                    # 保留字段；v7 起接听/挂断立即恢复，不再延迟
HINT_WINDOW=30            # VoIP 推送式来电提示的最长兜底窗口（秒）

# ---------- 来电强震铃音 ----------
# 来电时循环播放满幅震动，补偿系统铃声震动偏弱的问题
RING_PLAY=1               # 兼容字段；与 CALL_BOOST 共用一个 UI 开关
RING_DUR=1000             # 单次震动时长（ms，100 ~ 3000）
RING_GAP=1000             # 两次震动之间的间隔（ms，0 ~ 3000）
